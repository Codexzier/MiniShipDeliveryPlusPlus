// Sucht die Pixeldaten zu einer Unicode-Zeichennummer
const Glyph& findGlyph(std::uint32_t codepoint) {  // Beginn von findGlyph
    if (codepoint >= 32 && codepoint <= 126) return ASCII_GLYPHS[codepoint - 32]; // Normales ASCII-Zeichen
    for (const SpecialGlyph& special : SPECIAL_GLYPHS) { // Sonderzeichen durchsuchen
        if (special.codepoint == codepoint) return special.rows; // Treffer gefunden
    }                                              // Ende der Suche
    return ASCII_GLYPHS['?' - 32];                 // Unbekanntes Zeichen als Fragezeichen anzeigen
} // Ende von findGlyph

