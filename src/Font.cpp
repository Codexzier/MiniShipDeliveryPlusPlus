// Zerlegt einen UTF-8-kodierten Text in einzelne Unicode-Zeichennummern
std::vector<std::uint32_t> decodeUtf8(const std::string& text) { // Beginn von decodeUtf8
    std::vector<std::uint32_t> result;             // Ergebnisliste
    std::size_t i = 0;                             // Aktuelle Position im Text
    while (i < text.size()) {                      // Bis zum Textende
        unsigned char c = static_cast<unsigned char>(text[i]); // Aktuelles Byte
        std::uint32_t cp = '?';                    // Zeichennummer (Ersatzwert bei Fehlern)
        int extra = 0;                             // Anzahl der Folgebytes
        if (c < 0x80) { cp = c; extra = 0; }       // 1-Byte-Zeichen (ASCII)
        else if ((c & 0xE0) == 0xC0) { cp = c & 0x1F; extra = 1; } // 2-Byte-Zeichen (z.B. Umlaute)
        else if ((c & 0xF0) == 0xE0) { cp = c & 0x0F; extra = 2; } // 3-Byte-Zeichen (z.B. Euro)
        else if ((c & 0xF8) == 0xF0) { cp = c & 0x07; extra = 3; } // 4-Byte-Zeichen
        ++i;                                       // Erstes Byte verarbeitet
        for (int k = 0; k < extra && i < text.size(); ++k, ++i) { // Folgebytes einlesen
            cp = (cp << 6) | (static_cast<unsigned char>(text[i]) & 0x3F); // Je 6 Bit anhängen
        }                                          // Ende der Folgebyte-Schleife
        result.push_back(cp);                      // Zeichennummer speichern
    }                                              // Ende der Schleife
    return result;                                 // Liste zurückgeben
} // Ende von decodeUtf8

// Zeichnet einen Text; jedes Schriftpixel wird zu einem Quadrat der Größe scale x scale
void drawText(Canvas& canvas, int x, int y, const std::string& text, Color color, int scale) { // Beginn von drawText
    int penX = x;                                  // Aktuelle Schreibposition
    for (std::uint32_t cp : decodeUtf8(text)) {    // Alle Zeichen des Textes
        if (cp == '\n') { penX = x; y += LINE_HEIGHT * scale; continue; } // Zeilenumbruch
        const Glyph& glyph = findGlyph(cp);        // Pixeldaten des Zeichens holen
        for (int row = 0; row < GLYPH_HEIGHT; ++row) { // Alle Zeilen des Zeichens
            std::uint8_t bits = glyph[static_cast<std::size_t>(row)]; // Bitmuster der Zeile
            if (bits == 0) continue;               // Leere Zeile überspringen
            for (int col = 0; col < GLYPH_WIDTH; ++col) { // Alle Spalten der Zeile
                if (bits & (1 << (GLYPH_WIDTH - 1 - col))) { // Ist dieses Pixel gesetzt?
                    canvas.fillRect(penX + col * scale, y + row * scale, scale, scale, color); // Vergrößertes Pixel zeichnen
                }                                  // Ende der Pixelprüfung
            }                                      // Ende der Spaltenschleife
        }                                          // Ende der Zeilenschleife
        penX += ADVANCE * scale;                   // Schreibposition zum nächsten Zeichen verschieben
    }                                              // Ende der Zeichenschleife
} // Ende von drawText

// Zeichnet einen Text mit einem dunklen Schatten darunter (besser lesbar auf bunten Hintergründen)
void drawTextShadow(Canvas& canvas, int x, int y, const std::string& text, Color color, Color shadow, int scale) { // Beginn von drawTextShadow
    drawText(canvas, x + scale, y + scale, text, shadow, scale); // Schatten leicht versetzt zeichnen
    drawText(canvas, x, y, text, color, scale);    // Eigentlichen Text darüber zeichnen
} // Ende von drawTextShadow

// Berechnet die Breite der längsten Zeile eines Textes in Pixel
int textWidth(const std::string& text, int scale) { // Beginn von textWidth
    int longest = 0;                               // Längste Zeile (in Zeichen)
    int current = 0;                               // Länge der aktuellen Zeile
    for (std::uint32_t cp : decodeUtf8(text)) {    // Alle Zeichen durchgehen
        if (cp == '\n') { current = 0; continue; } // Neue Zeile beginnt
        ++current;                                 // Zeichen zählen
        longest = std::max(longest, current);      // Längste Zeile merken
    }                                              // Ende der Schleife
    if (longest == 0) return 0;                    // Leerer Text hat keine Breite
    return (longest * ADVANCE - 1) * scale;        // Breite ohne die Lücke nach dem letzten Zeichen
} // Ende von textWidth

int lineHeight(int scale) { return LINE_HEIGHT * scale; } // Zeilenhöhe = Grundhöhe mal Skalierung

// Bricht einen Text so um, dass keine Zeile breiter als maxWidth Pixel ist
std::vector<std::string> wrap(const std::string& text, int maxWidth, int scale) { // Beginn von wrap
    std::vector<std::string> lines;                // Ergebniszeilen
    std::istringstream stream(text);               // Text als Datenstrom
    std::string word;                              // Aktuelles Wort
    std::string current;                           // Aktuelle Zeile
    while (stream >> word) {                       // Wort für Wort lesen (Leerzeichen trennen)
        std::string candidate = current.empty() ? word : current + " " + word; // Zeile mit dem neuen Wort
        if (!current.empty() && textWidth(candidate, scale) > maxWidth) { // Passt das Wort nicht mehr in die Zeile?
            lines.push_back(current);              // Bisherige Zeile abschließen
            current = word;                        // Neues Wort beginnt die nächste Zeile
        } else {                                   // Wort passt noch
            current = candidate;                   // Zeile verlängern
        }                                          // Ende der Unterscheidung
    }                                              // Ende der Wortschleife
    if (!current.empty()) lines.push_back(current); // Letzte Zeile übernehmen
    return lines;                                  // Zeilen zurückgeben
} // Ende von wrap

